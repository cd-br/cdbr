/** Traduz uma chave para o idioma atual. */
export function t(chave) {
  const idioma = obterIdiomaAtual();
  return TEXTOS[idioma]?.[chave] ?? TEXTOS.en[chave] ?? chave;
}

/** Aplica os textos em todo elemento marcado com data-i18n / data-i18n-placeholder / data-i18n-aria. */
export function aplicarTraducaoEstatica() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  document.documentElement.lang = obterIdiomaAtual() === 'pt' ? 'pt-BR' : 'en';
}
